  'watermelon_seed', 'groundnuts_seed', 'sesame_seed', 'pepper_seed', 'herbs_seed',
  'morula_seed', 'sorghum', 'millet', 'maize', 'cowpeas', 'tomatoes', 'watermelon',
  'groundnuts', 'sesame', 'pepper', 'herbs', 'morula', 'eggs', 'milk', 'truffle',
  'manure', 'wood', 'hardwood', 'stone', 'clay', 'palm_fiber', 'thatch', 'phane',
  'poleto', 'thapo', 'setena', 'bupi', 'borotho'
);

