-- Reconcile market_prices with the authoritative @molemisi/game-config catalogue.
--
-- Background (docs/26_Inventory_Crafting_System.md §11.1): the Co-op market is the
-- read/write surface for the inventory system. Every non-tool item must have exactly
-- one market_prices row whose base_price equals the item's ItemDef.baseValue, and no
-- row may reference a slug that no longer exists in the catalogue.
--
-- The two historical seeders (migration 20260902000003_market_dynamic_pricing.sql and
-- supabase/seed/seed.sql) were written for a PRE-REFACTOR economy and had drifted hard:
--   * Orphan rows for items that do not exist (saffron, saffron_seed, wool, honey,
--     herb_bundle, wild_saffron, egg, goat_milk, cow_milk, flour, butter, cheese,
--     leather, bread).
--   * Missing rows for real sellable items (morula, eggs, milk, manure, hardwood,
--     clay, palm_fiber, thatch, phane, poleto, thapo, setena, bupi, borotho) — so
--     getDynamicPrice() returned 0 and the Co-op refused to quote/sell them.
--   * Wrong base_price on every crop/seed/milk/wood/stone row (4-8x the catalogue).
--
-- This migration is generated by scripts/generate-market-seed.cjs so the row list stays
-- in lock-step with the catalogue; re-run the script and this migration together if the
-- catalogue changes. It is idempotent: safe to re-apply.
--
-- NOTE: `current_price` is reset to base_price because the live values in the table are
-- the stale pre-refactor numbers and carry no legitimate market signal. Live drift
-- resumes from the service's 6-hour cycle after this runs.

-- 1) Remove orphan rows: any slug currently in market_prices that is not in the catalogue.
