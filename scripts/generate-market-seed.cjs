/**
 * generate-market-seed.cjs
 *
 * Reconciliation tool: emits the canonical `market_prices` seed rows DIRECTLY
 * from the authoritative @molemisi/game-config catalogue (packages/game-config/dist),
 * so the Co-op market can never drift from the inventory system again.
 *
 * Rules (mirrors docs/26_Inventory_Crafting_System.md §2.1 / §11.1):
 *   - Every non-tool item gets exactly one row.
 *   - base_price = the item's ItemDef.baseValue (the price of record).
 *   - Seeds (DIPEO) get a row because they are BUYABLE, but the Co-op sell path
 *     must reject them (see MarketService.sellItem guard) — they are not sellable.
 *   - Tools (DIDIRISIWA) are equipment: not stored, not in market_prices.
 *   - current_price is seeded to base_price; live drift is added by the service.
 *
 * Usage:
 *   node scripts/generate-market-seed.cjs            # prints migration + seed.sql block
 *   node scripts/generate-market-seed.cjs migration  # only the reconciliation migration
 *   node scripts/generate-market-seed.cjs seed       # only the seed.sql INSERT block
 */
const gc = require('../packages/game-config/dist/index.js');
const { ITEMS } = gc;

const MARKET_CATEGORY = {
  DIPEO: 'seed',
  DIJALO: 'crop',
  DIPHOLOGOLO: 'product',
  'DITSHIMOLOGO TSA NAGENG': 'material',
  DITSALO: 'crafted',
  DIKUNO: 'crafted',
  // DIDIRISIWA is intentionally excluded below.
};

function esc(s) {
  return String(s).replace(/'/g, "''");
}

// Canonical rows, in catalogue category order for readability.
const ORDER = ['DIPEO', 'DIJALO', 'DIPHOLOGOLO', 'DITSHIMOLOGO TSA NAGENG', 'DITSALO', 'DIKUNO'];
const rows = [];
for (const cat of ORDER) {
  for (const item of Object.values(ITEMS).filter((i) => i.category === cat)) {
    rows.push({
      slug: item.slug,
      name: item.name,
      base: item.baseValue,
      marketCat: MARKET_CATEGORY[cat],
    });
  }
}

const canonSlugs = rows.map((r) => `'${r.slug}'`).join(', ');
const valuesTuples = rows
  .map((r) => `  ('${r.slug}', '${esc(r.name)}', ${r.base}, ${r.base}, '${r.marketCat}')`)
  .join(',\n');

const mode = process.argv[2] || 'all';

if (mode === 'all' || mode === 'migration') {
  console.log(`-- Reconciliation migration: align market_prices with the @molemisi/game-config catalogue.
-- Generated by scripts/generate-market-seed.cjs — do not hand-edit the row list.
-- 1) Drop orphan rows (slugs that exist in market_prices but not in the catalogue).
-- 2) Upsert every canonical row; correct stale base_price/current_price to baseValue.`);
  console.log(`DELETE FROM public.market_prices
WHERE item_type NOT IN (${canonSlugs});`);
  console.log('');
  console.log(`INSERT INTO public.market_prices (item_type, item_name, base_price, current_price, category)
VALUES
${valuesTuples}
ON CONFLICT (item_type) DO UPDATE SET
  base_price = EXCLUDED.base_price,
  current_price = EXCLUDED.base_price,
  item_name = EXCLUDED.item_name,
  category = EXCLUDED.category,
  updated_at = NOW();`);
  console.log('');
}

if (mode === 'all' || mode === 'seed') {
  console.log(`-- seed.sql market_prices block (canonical, generated by scripts/generate-market-seed.cjs).
-- ON CONFLICT DO NOTHING so it is harmless after the reconciliation migration has run.`);
  console.log(`INSERT INTO public.market_prices (item_type, item_name, base_price, current_price, category)
VALUES
${valuesTuples}
ON CONFLICT (item_type) DO NOTHING;`);
  console.log('');
}

if (mode === 'all') {
  console.log(`-- Canonical row count: ${rows.length} (42 catalogue items − 4 tools = 38).`);
}
